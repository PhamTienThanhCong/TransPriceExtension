export const ICON_NAMES = Object.freeze([...Object.keys(PATHS), ...Object.keys(ALIASES), ...Object.keys(FILLED), 'star-filled']);

/**
 * Static SVG markup for an icon (trusted, safe for insertAdjacentHTML).
 * @param {string} name  icon name (see ICON_NAMES); 'star-filled' = solid star
 * @param {{size?: number, className?: string, strokeWidth?: number}} [opts]
 */
export function iconHTML(name, { size = 18, className = '', strokeWidth = 2 } = {}) {
  name = ALIASES[name] || name;
  const safe = (v) => String(v).replace(/[^\w -]/g, ''); // the markup is trusted: never let a caller break out of it
  size = Number(size) || 18;
  strokeWidth = Number(strokeWidth) || 2;
  const cls = `icon icon-${safe(name)}${className ? ` ${safe(className)}` : ''}`;
  const common = `xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" class="${cls}" aria-hidden="true" focusable="false"`;
  if (name === 'star-filled') {
    return `<svg ${common} fill="currentColor" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linejoin="round">${PATHS.star}</svg>`;
  }
  if (FILLED[name]) {
    return `<svg ${common} fill="currentColor">${FILLED[name]}</svg>`;
  }
  const body = PATHS[name];
  if (!body) {
    console.warn(`[TransPrice] Unknown icon: ${name}`);
    return `<svg ${common}></svg>`;
  }
  return `<svg ${common} fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
}

const template = typeof document !== 'undefined' ? document.createElement('template') : null;

/** SVGElement for an icon (`opts` as for iconHTML: `{ size, className, strokeWidth }`). */
export function icon(name, opts) {
  template.innerHTML = iconHTML(name, opts); // trusted-html: static markup, class names sanitized
  return template.content.firstElementChild;
}

/** Replace every `<i data-icon="name" [data-icon-size="16"]>` placeholder inside `root` with the SVG. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach((el) => {
    const size = Number(el.dataset.iconSize) || undefined;
    const svg = icon(el.dataset.icon, { size, className: el.className || '' });
    el.replaceWith(svg);
  });
}
